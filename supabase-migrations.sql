-- ============================================================
-- SUPABASE MIGRATION: Cost Centers + Driver-Vehicle Linking
-- Run this in Supabase SQL Editor
-- ============================================================

-- 1. Cost Centers table (new)
CREATE TABLE IF NOT EXISTS cost_centers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  code TEXT UNIQUE NOT NULL,
  description TEXT,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Add fleet_number to drivers (links driver to their assigned vehicle)
ALTER TABLE drivers ADD COLUMN IF NOT EXISTS fleet_number TEXT;

-- 3. Add cost_center_id to drivers (FK to cost_centers)
ALTER TABLE drivers ADD COLUMN IF NOT EXISTS cost_center_id BIGINT REFERENCES cost_centers(id);

-- 4. Add cost_center_id to vehiclesc (FK to cost_centers)
ALTER TABLE vehiclesc ADD COLUMN IF NOT EXISTS cost_center_id BIGINT REFERENCES cost_centers(id);

-- 5. Migrate existing cost_center text values in vehiclesc to FK
UPDATE vehiclesc v
SET cost_center_id = cc.id
FROM cost_centers cc
WHERE LOWER(v.cost_center) = LOWER(cc.code)
  AND v.cost_center_id IS NULL;

-- 6. Indexes
CREATE INDEX IF NOT EXISTS idx_cost_centers_code ON cost_centers(code);
CREATE INDEX IF NOT EXISTS idx_drivers_fleet_number ON drivers(fleet_number);
CREATE INDEX IF NOT EXISTS idx_drivers_cost_center ON drivers(cost_center_id);
CREATE INDEX IF NOT EXISTS idx_vehiclesc_cost_center_id ON vehiclesc(cost_center_id);

-- 7. Vehicle-lookup view: joins vehicle + driver + cost center in one query
CREATE OR REPLACE VIEW vehicle_driver_lookup AS
SELECT
  v.id AS vehicle_id,
  v.fleet_number,
  v.registration_number,
  v.make,
  v.model,
  v.cost_center AS cost_center_text,
  v.cost_center_id,
  v.driver_id,
  v.camera_serial,
  v.camera_sim_id,
  d.id AS driver_id_num,
  d.first_name AS driver_first_name,
  d.surname AS driver_surname,
  d.cell_number AS driver_cell,
  d.license_number AS driver_license,
  d.license_expiry_date AS driver_license_expiry,
  d.cost_center_id AS driver_cost_center_id,
  cc.name AS cost_center_name,
  cc.code AS cost_center_code
FROM vehiclesc v
LEFT JOIN drivers d ON d.id = v.driver_id
LEFT JOIN cost_centers cc ON cc.id = COALESCE(v.cost_center_id, d.cost_center_id);
